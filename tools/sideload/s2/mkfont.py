# Regenerates font.h (10x19 bitmap font for the test card) from DejaVu Sans Mono Bold.
# python3 mkfont.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf
import sys
from PIL import Image, ImageDraw, ImageFont
f = ImageFont.truetype(sys.argv[1], 16)
W, H = 10, 19
rows = []
for c in range(32, 127):
    im = Image.new('L', (W, H), 0)
    ImageDraw.Draw(im).text((0, 0), chr(c), font=f, fill=255)
    rows.append([sum(1 << (15 - x) for x in range(W) if im.getpixel((x, y)) > 110) for y in range(H)])
with open('font.h', 'w') as o:
    o.write('// 10x19 bitmap font, ASCII 32-126, rendered from DejaVu Sans Mono Bold\n')
    o.write('// (Bitstream Vera / DejaVu font licence: free to use and embed).\n')
    o.write('// One uint16_t per row, bit 15 = leftmost pixel. Generated by mkfont.py.\n')
    o.write('#pragma once\n#include <stdint.h>\nenum { kFontW = %d, kFontH = %d };\n' % (W, H))
    o.write('static const uint16_t kFont[95][%d] = {\n' % H)
    for r in rows:
        o.write('  {' + ','.join('0x%04x' % v for v in r) + '},\n')
    o.write('};\n')
